/**
 * @file emitter-thumb.h
 * @brief Thumb instruction table layout macros.
 *
 * DECLARE_THUMB_EMITTER_BLOCK(EMITTER) expands to 1024 comma-separated
 * function pointers indexed by opcode >> 6.
 */

