#!/usr/bin/env python3
"""Reproduce the signed 1.14 sine values used by the affine firmware."""
# SPDX-License-Identifier: GPL-3.0-or-later
from decimal import Decimal, localcontext
from pathlib import Path
import argparse


def sine_values():
    with localcontext() as context:
        context.prec = 64
        pi = Decimal("3.141592653589793238462643383279502884197169399375105820974944592")
        quadrant = [0]
        for angle in range(1, 64):
            x = pi * angle / 128
            term = total = x
            for n in range(1, 80):
                term *= -x * x / ((2 * n) * (2 * n + 1))
                total += term
            quadrant.append(int(total * 16384))
        quadrant.append(16384)
        return [quadrant[i] for i in range(64)] + [quadrant[64-i] for i in range(64)] + \
            [-quadrant[i] for i in range(64)] + [-quadrant[64-i] for i in range(64)]


def render():
    values = sine_values()
    lines = ["@ Signed 1.14 sine values; generated by tests/bios/generate_affine_table.py.",
             "@ SPDX-License-Identifier: GPL-3.0-or-later"]
    for index in range(0, 256, 8):
        lines.append(".hword " + ", ".join(str(value) for value in values[index:index+8]))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    options = parser.parse_args()
    destination = Path(__file__).resolve().parents[2] / "src/gba/bios/affine-sine.inc"
    expected = render().encode("utf-8")
    if options.write:
        destination.write_bytes(expected)
    elif destination.read_bytes() != expected:
        raise SystemExit("Affine sine table differs from its mathematical generator")
    else:
        print("Verified 256 affine sine values")
