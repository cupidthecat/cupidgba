#!/usr/bin/env python3
"""Reproduce the fixed-point semitone factors and octave indices."""
# SPDX-License-Identifier: GPL-3.0-or-later
import argparse
from decimal import Decimal, ROUND_HALF_UP, localcontext
from pathlib import Path


def factors():
    with localcontext() as context:
        context.prec = 96
        return [int((Decimal(2) ** (Decimal(note) / 12) * (1 << 31)).to_integral_value(rounding=ROUND_HALF_UP))
                for note in range(12)]


def render():
    indices = [((14 - note // 12) << 4) | (note % 12) for note in range(180)]
    lines = ["@ Fixed-point pitch data; generated by tests/bios/generate_music_table.py.",
             "@ SPDX-License-Identifier: GPL-3.0-or-later", "musicPitchIndices:"]
    for start in range(0, len(indices), 12):
        lines.append(".byte " + ", ".join(f"0x{value:02X}" for value in indices[start:start+12]))
    lines.extend([".balign 4, 0", "musicSemitoneFactors:"])
    lines.extend(f".word 0x{value:08X}" for value in factors())
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    options = parser.parse_args()
    destination = Path(__file__).resolve().parents[2] / "src/gba/bios/music-pitch.inc"
    expected = render().encode("utf-8")
    if options.write:
        destination.write_bytes(expected)
    elif destination.read_bytes() != expected:
        raise SystemExit("Music pitch table differs from its mathematical generator")
    else:
        print("Verified 180 pitch indices and 12 semitone factors")
